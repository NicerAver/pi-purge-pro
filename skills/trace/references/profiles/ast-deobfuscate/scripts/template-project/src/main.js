#!/usr/bin/env node

const fs = require('fs')
const path = require('path')

const { detectFamily, generateCode, parseCode, parseStrict } = require('./lib/core')
const runCommon = require('./plugins/common')
const runAwsc = require('./plugins/awsc')
const runObfuscator = require('./plugins/obfuscator')
const runSojson = require('./plugins/sojson')
const runSojsonV7 = require('./plugins/sojsonv7')

const pipelines = {
  common: runCommon,
  awsc: runAwsc,
  obfuscator: runObfuscator,
  sojson: runSojson,
  sojsonv7: runSojsonV7
}

function getArg(flag, fallback) {
  const index = process.argv.indexOf(flag)
  if (index === -1 || index + 1 >= process.argv.length) return fallback
  return process.argv[index + 1]
}

function safeStepName(name) {
  return String(name).replace(/[^a-z0-9_-]+/gi, '-').replace(/^-+|-+$/g, '') || 'pass'
}

function main() {
  const inputFile = getArg('-i', path.resolve(process.cwd(), 'input.js'))
  const outputFile = getArg('-o', path.resolve(process.cwd(), 'output.js'))
  const referenceFile = getArg('--reference', '')
  const stepsDir = getArg('--steps', '')
  const code = fs.readFileSync(inputFile, 'utf8')

  const family = detectFamily(code)
  const transform = pipelines[family] || runCommon
  const options = {}
  if (stepsDir) {
    fs.mkdirSync(stepsDir, { recursive: true })
    options.onPass = ({ index, name, code: stepCode }) => {
      const file = `${String(index).padStart(2, '0')}-${safeStepName(name)}.js`
      fs.writeFileSync(path.join(stepsDir, file), `${stepCode}\n`, 'utf8')
    }
  }
  const result = generateCode(transform(parseCode(code), options))
  parseStrict(result)

  if (referenceFile) {
    const expected = generateCode(parseStrict(fs.readFileSync(referenceFile, 'utf8')))
    const actual = generateCode(parseStrict(result))
    if (actual !== expected) {
      throw new Error(`canonical AST fixture mismatch: ${referenceFile}`)
    }
  }

  const banner = [
    '// generated by decode_action template-project',
    `// plugin: ${family}`,
    `// input: ${path.basename(inputFile)}`,
    ''
  ].join('\n')

  fs.mkdirSync(path.dirname(path.resolve(outputFile)), { recursive: true })
  fs.writeFileSync(outputFile, banner + result, 'utf8')
  console.log(`plugin=${family}`)
  console.log(`output=${outputFile}`)
  if (stepsDir) console.log(`steps=${stepsDir}`)
}

main()
